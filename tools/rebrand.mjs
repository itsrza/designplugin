#!/usr/bin/env node
/**
 * Rebrand the plugin without touching its technical identifiers.
 *
 *   node tools/rebrand.mjs --dry-run         # report only (default)
 *   node tools/rebrand.mjs --write           # backup + apply + rebuild *.min.*
 *   node tools/rebrand.mjs --config other.json
 *
 * What it does:
 *  - rewrites brand colours everywhere they live in the plugin CSS/JS/PHP,
 *    including the navy-derived rgba() shadows when `"rgbShadows": true`;
 *  - rewrites plain-text tokens (phone numbers, brand name, CTA copy) in the
 *    source files;
 *  - never touches *.min.* files (they are regenerated by tools/build.mjs),
 *    shortcode names, REST namespaces or URL parameters.
 *
 * Safety: default mode is a dry run; --write copies every file it changes to
 * rebrand-backup/<timestamp>/ first, so `cp -r` back is a full revert.
 */
import { readFile, writeFile, readdir, mkdir, copyFile, stat } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN = path.join(ROOT, 'serviya');
const argv = process.argv.slice(2);
const WRITE = argv.includes('--write');
const configIndex = argv.indexOf('--config');
const CONFIG_PATH = path.resolve(ROOT, configIndex >= 0 ? argv[configIndex + 1] : 'rebrand.config.json');

const EXTENSIONS = new Set(['.css', '.js', '.php', '.md']);

function normalizeHex(value) {
  return String(value || '').trim().toUpperCase();
}

function hexToRgb(hex) {
  const clean = normalizeHex(hex).replace('#', '');
  if (!/^[0-9A-F]{6}$/.test(clean)) return null;
  return [0, 2, 4].map((i) => parseInt(clean.slice(i, i + 2), 16));
}

function rgbToHex([r, g, b]) {
  return '#' + [r, g, b].map((n) => Math.max(0, Math.min(255, n)).toString(16).padStart(2, '0')).join('').toUpperCase();
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

const config = JSON.parse(await readFile(CONFIG_PATH, 'utf8'));

/* ------------------------------------------------------------------ rules */

const rules = [];

for (const [from, to] of Object.entries(config.colors || {})) {
  const source = normalizeHex(from);
  const target = normalizeHex(to);
  if (!/^#[0-9A-F]{6}$/.test(source) || !/^#[0-9A-F]{6}$/.test(target)) {
    console.warn(`! colour pair ignored (need #RRGGBB): ${from} → ${to}`);
    continue;
  }
  if (source === target) continue; // identity mapping: nothing to rewrite
  rules.push({
    label: `color ${source} → ${target}`,
    // #RRGGBB only; the boundaries keep #B7E600 from matching inside longer tokens.
    pattern: new RegExp(source.replace('#', '\\#'), 'gi'),
    replace: target,
    files: (name) => /\.(css|js|php)$/.test(name),
  });
}

// rgba(24,35,61,…) shadows follow the navy colour.
if (config.rgbShadows && config.colors) {
  for (const [from, to] of Object.entries(config.colors)) {
    const sourceRgb = hexToRgb(from);
    const targetRgb = hexToRgb(to);
    if (!sourceRgb || !targetRgb || normalizeHex(from) === normalizeHex(to)) continue;
    rules.push({
      label: `shadow rgba(${sourceRgb.join(',')}) → rgba(${targetRgb.join(',')})`,
      pattern: new RegExp(
        `rgba\\(\\s*${sourceRgb[0]}\\s*,\\s*${sourceRgb[1]}\\s*,\\s*${sourceRgb[2]}\\s*,`,
        'gi'
      ),
      replace: `rgba(${targetRgb[0]},${targetRgb[1]},${targetRgb[2]},`,
      files: (name) => /\.(css|js|php)$/.test(name),
    });
  }
}

for (const item of config.replacements || []) {
  if (!item || !item.find) continue;
  if (item.find === (item.replace ?? '')) continue; // no-op
  rules.push({
    label: `text ${JSON.stringify(item.find)} → ${JSON.stringify(item.replace ?? '')}`,
    pattern: new RegExp(item.find.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), item.regex ? 'g' : 'g'),
    replace: item.replace ?? '',
    // Optional per-rule scope, e.g. ["modules/product.php", "assets/js/*.js"].
    files: item.files
      ? ((list) => (name) => list.some((glob) => globToRegExp(glob).test(name)))(item.files)
      : ((name) => /\.(css|js|php|md)$/.test(name)),
  });
}

function globToRegExp(glob) {
  const escaped = glob
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*/g, '\u0000')
    .replace(/\*/g, '[^/]*')
    .replace(/\u0000/g, '.*');
  return new RegExp(`^${escaped}$`);
}

/* ------------------------------------------------------------------- apply */

const files = (await walk(PLUGIN)).filter(
  (file) => EXTENSIONS.has(path.extname(file)) && !/\.min\.(css|js)$/.test(file)
);

const backupDir = path.join(ROOT, 'rebrand-backup', new Date().toISOString().replace(/[:.]/g, '-'));
let changedFiles = 0;
let totalHits = 0;
const report = [];

for (const file of files) {
  const relative = path.relative(ROOT, file);
  const name = path.relative(PLUGIN, file);
  const original = await readFile(file, 'utf8');
  let content = original;
  const hits = [];

  for (const rule of rules) {
    if (!rule.files(name)) continue;
    const matches = content.match(rule.pattern);
    if (!matches) continue;
    hits.push({ rule: rule.label, count: matches.length });
    content = content.replace(rule.pattern, rule.replace);
  }

  if (!hits.length) continue;

  changedFiles += 1;
  totalHits += hits.reduce((sum, hit) => sum + hit.count, 0);
  report.push({ file: relative, hits });

  if (WRITE) {
    const target = path.join(backupDir, path.relative(ROOT, file));
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(file, target);
    await writeFile(file, content, 'utf8');
  }
}

/* ------------------------------------------------------------------ output */

if (!report.length) {
  console.log('Nothing to change — the config does not match any file.');
  process.exit(0);
}

for (const entry of report) {
  console.log(`\n${entry.file}`);
  for (const hit of entry.hits) console.log(`   ${String(hit.count).padStart(3)} ×  ${hit.rule}`);
}

console.log(
  `\n${WRITE ? 'Applied' : 'Would apply'} ${totalHits} replacement(s) in ${changedFiles} file(s).`
);

if (!WRITE) {
  console.log('Dry run only. Re-run with --write to apply (a backup is written to rebrand-backup/).');
  process.exit(0);
}

const backupStat = await stat(backupDir).catch(() => null);
if (backupStat) console.log(`Backup: ${path.relative(ROOT, backupDir)}`);

// Regenerate the minified builds so the shipped assets match the sources.
const build = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'build.mjs')], {
  cwd: ROOT,
  stdio: 'inherit',
});
if (build.status !== 0) {
  console.error('\nAsset build failed — sources are rebranded but *.min.* are stale.');
  process.exit(build.status || 1);
}

console.log('\nNext: npm run check  →  npm run package');
